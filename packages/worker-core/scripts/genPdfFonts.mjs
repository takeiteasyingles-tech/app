// Regenerates src/pdf/fonts.gen.ts: the self-hosted brand fonts (packages/ui/fonts, latin subset) as
// TrueType, base64-encoded, for the certificate PDF (src/pdf/certificate.ts). PDF viewers need
// TrueType/OpenType outlines (FontFile2), not WOFF2, and @pdf-lib/fontkit cannot subset WOFF2, so the
// files are decompressed here once with Google's woff2 decoder (the wawoff2 WebAssembly build):
//   npm i --no-save wawoff2@2.0.1
//   node packages/worker-core/scripts/genPdfFonts.mjs
// Figtree is a variable font: the PDF shows its default instance (wght 300, Light).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { decompress } from 'wawoff2';

const fonts = fileURLToPath(new URL('../../ui/fonts/', import.meta.url));
const out = fileURLToPath(new URL('../src/pdf/fonts.gen.ts', import.meta.url));

const ttf = async (file) => Buffer.from(await decompress(readFileSync(fonts + file))).toString('base64');

const archivo = await ttf('archivo-latin.woff2');
const figtree = await ttf('figtree-latin.woff2');

writeFileSync(
  out,
  `// GENERATED by scripts/genPdfFonts.mjs from packages/ui/fonts/*-latin.woff2. Do not edit.
// Both fonts are under the SIL Open Font License 1.1.

/** Archivo Black Italic (wght 900), latin subset, TrueType. The brand display face. */
export const ARCHIVO_BLACK_ITALIC_TTF = '${archivo}';

/** Figtree (variable wght 300..900; default instance Light 300), latin subset, TrueType. */
export const FIGTREE_TTF = '${figtree}';
`,
);
console.log(`wrote ${out} (${archivo.length + figtree.length} base64 chars)`);
